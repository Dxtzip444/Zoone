// embedded Selawik fonts.
//   node build.mjs            -> writes user.css
//   node build.mjs --install  -> also copies the theme to Spicetify's Themes/Zoone
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const themeDir = here; // the repository root is the theme

// Selawik: Microsoft's open (SIL OFL 1.1) metric-compatible stand-in for Segoe UI.
const faces = [
  { file: "selawkl.woff2", weight: 300 },
  { file: "selawksl.woff2", weight: 350 },
  { file: "selawk.woff2", weight: 400 },
  { file: "selawksb.woff2", weight: 600 },
  { file: "selawkb.woff2", weight: 700 },
];

const fontCss = faces
  .map(({ file, weight }) => {
    const b64 = readFileSync(join(here, "fonts", file)).toString("base64");
    // Selawik's U+2026 draws one dot, so every ellipsis looked like a period:
    // leave that character to the next font in the stack
    return `@font-face{font-family:"Zune Selawik";font-style:normal;font-weight:${weight};font-display:swap;unicode-range:U+0000-2025,U+2027-10FFFF;src:url(data:font/woff2;base64,${b64}) format("woff2")}`;
  })
  .join("\n");

// Both schemes from color.ini, as classes on <html>. Spicetify's colors.css
// carries only the scheme picked with `spicetify config color_scheme`; these
// let Settings > colors > theme switch to the other one without an apply.
function palettes() {
  const ini = readFileSync(join(themeDir, "color.ini"), "utf8");
  const schemes = {};
  let cur = null;
  for (const raw of ini.split(/\r?\n/)) {
    const line = raw.replace(/;.*$/, "").trim();
    if (!line) continue;
    const sec = line.match(/^\[([^\]]+)\]$/);
    if (sec) {
      cur = schemes[sec[1].trim()] = {};
      continue;
    }
    const kv = line.match(/^([\w-]+)\s*=\s*([0-9a-fA-F]{6})$/);
    if (cur && kv) cur[kv[1]] = kv[2].toLowerCase();
  }
  return ["light", "dark"]
    .filter((name) => schemes[name])
    .map((name) => {
      const decls = Object.entries(schemes[name]).flatMap(([k, hex]) => {
        const rgb = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(", ");
        return [`  --spice-${k}: #${hex};`, `  --spice-rgb-${k}: ${rgb};`];
      });
      return `html.zune-palette-${name} {\n${decls.join("\n")}\n}`;
    })
    .join("\n");
}

const css = readFileSync(join(here, "src", "zoone.css"), "utf8");
const out = `${css.trimEnd()}

/* --------------------------------------------------------------------------
   Schemes from color.ini, for Settings > colors > theme.
   Generated by build.mjs; edit Zune/color.ini instead of this block.
   -------------------------------------------------------------------------- */
${palettes()}

/* --------------------------------------------------------------------------
   Embedded font: Selawik (c) 2015 Microsoft Corporation, SIL Open Font
   License 1.1 (see fonts/LICENSE-Selawik.txt). Used when Segoe UI is absent.
   Generated by build.mjs; edit src/zune.css instead of this block.
   -------------------------------------------------------------------------- */
${fontCss}
`;

writeFileSync(join(themeDir, "user.css"), out);
console.log(`wrote user.css (${(out.length / 1024).toFixed(0)} KB)`);

if (process.argv.includes("--install")) {
  const base =
    process.platform === "win32"
      ? join(process.env.APPDATA || join(homedir(), "AppData", "Roaming"), "spicetify", "Themes")
      : join(process.env.XDG_CONFIG_HOME || join(homedir(), ".config"), "spicetify", "Themes");
  const dest = join(base, "Zoone");
  mkdirSync(join(dest, "fonts"), { recursive: true });
  for (const f of ["color.ini", "user.css", "theme.js", "fonts/LICENSE-Selawik.txt"]) {
    const src = join(themeDir, f);
    if (existsSync(src)) copyFileSync(src, join(dest, f));
  }
  console.log(`installed to ${dest}`);
}
